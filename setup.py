#!/usr/bin/env python3
"""
PageDuel API key setup for the Omarchy Live Visitors widget.

Usage:
    python3 ~/.config/omarchy/plugins/nichovski.pageduel-live-visitors/setup.py
"""

import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

DEFAULT_API_BASE = "https://pageduel.com/api/v1"
CREDENTIALS_DIR = Path.home() / ".config" / "omarchy" / "pageduel"
CREDENTIALS_FILE = CREDENTIALS_DIR / "credentials.env"


def header(text):
    print(f"\n{'=' * 60}")
    print(f"  {text}")
    print(f"{'=' * 60}\n")


def validate_key(api_base, api_key):
    req = urllib.request.Request(
        f"{api_base}/sites",
        headers={"Authorization": f"Bearer {api_key}"},
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            json.loads(resp.read())
            return True, None
    except urllib.error.HTTPError as e:
        if e.code == 401:
            return False, "That key was rejected (401 — missing, invalid or revoked)."
        if e.code == 402:
            return False, "That key's plan doesn't include API access (402)."
        return False, f"Unexpected response (HTTP {e.code})."
    except Exception as e:
        return False, f"Could not reach {api_base}: {e}"


def save_credentials(api_key, api_base):
    CREDENTIALS_DIR.mkdir(parents=True, exist_ok=True)
    from datetime import datetime

    content = f"""# PageDuel Live Visitors widget credentials
# Generated by setup.py on {datetime.now().isoformat()}
# Do not edit manually — re-run setup.py to regenerate

PAGEDUEL_API_KEY={api_key}
PAGEDUEL_API_BASE={api_base}
"""
    CREDENTIALS_FILE.write_text(content)
    CREDENTIALS_FILE.chmod(0o600)


def main():
    header("PageDuel Live Visitors — Setup")

    print("  This widget shows how many visitors are on your PageDuel-")
    print("  tracked sites right now, in the Omarchy topbar.")
    print()
    print("  Create a key in PageDuel: Settings -> API keys")
    print("  (a read-only key, scoped to all sites, is enough)")
    print()

    api_key = input("  PageDuel API key (pd_...): ").strip()
    if not api_key:
        print("  x API key is required.")
        sys.exit(1)

    api_base = input(f"  API base URL [{DEFAULT_API_BASE}]: ").strip()
    if not api_base:
        api_base = DEFAULT_API_BASE
    api_base = api_base.rstrip("/")

    print("\n  Checking the key...")
    ok, message = validate_key(api_base, api_key)
    if not ok:
        print(f"  x {message}")
        print("  Saving anyway — the widget will show this same error")
        print("  until it can reach a working /api/v1/live endpoint.")

    save_credentials(api_key, api_base)

    print(f"\n{'=' * 60}")
    print("  Setup complete!")
    print(f"{'=' * 60}\n")
    print(f"  Credentials saved to: {CREDENTIALS_FILE}")
    print("  The widget is already in your bar layout and will update")
    print("  on its next poll.")
    print()
    print("  To reconfigure, re-run this script.")
    print()


if __name__ == "__main__":
    main()
